export const DICT_ES = {};
for (const line of RAW.split('\n')) {
  const i = line.indexOf('=');
  if (i < 1) continue;
  const k = line.slice(0, i).trim().toLowerCase();
  if (k && !DICT_ES[k]) DICT_ES[k] = line.slice(i + 1).trim();
}

